// --- shared code blocks -------------------------------------------------------------
function readCodeBlocks() {
  const text = readFileSync(join(docsDir, 'content', 'code.html'), 'utf8');
  const blocks = {};
  const parts = text.split(/<!-- @code ([\w-]+) -->\n/);
  for (let i = 1; i < parts.length; i += 2) blocks[parts[i]] = parts[i + 1].trim();
  return blocks;
}

// --- contents list from the headings -------------------------------------------------
const stripTags = (html) => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

function buildToc(main) {
  const items = [];
  const sectionRe = /<section id="([\w-]+)">\s*<h2 class="sec">([\s\S]*?)<\/h2>([\s\S]*?)<\/section>/g;
  for (const [, id, title, body] of main.matchAll(sectionRe)) {
    items.push(`<li><a href="#${id}">${stripTags(title)}</a></li>`);
    // only the h3 subsections of "How it works" go into the list (the rest stay short)
    if (id === 'concepts') {
      for (const [, subId, subTitle] of body.matchAll(/<h3 id="([\w-]+)">([\s\S]*?)<\/h3>/g)) {
        items.push(`<li class="sub"><a href="#${subId}">${stripTags(subTitle)}</a></li>`);
      }
    }
  }
  return items.join('\n          ');
}

