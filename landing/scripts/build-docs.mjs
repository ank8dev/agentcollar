// --- build -------------------------------------------------------------------------------
function parseMeta(text) {
  const m = text.match(/^<!--meta\n([\s\S]*?)\n-->\n/);
  if (!m) throw new Error('missing <!--meta ... --> header');
  const meta = Object.fromEntries(m[1].split('\n').map((line) => [line.split(':')[0].trim(), line.slice(line.indexOf(':') + 1).trim()]));
  return { meta, main: text.slice(m[0].length) };
}

const code = readCodeBlocks();
const built = [];
// a language without its content file yet is left out (and out of the switcher)
const available = LANGS.filter((l) => existsSync(join(docsDir, 'content', `${l.code}.html`)));
LANGS.splice(0, LANGS.length, ...available);
for (const lang of LANGS) {
  const { meta, main } = parseMeta(readFileSync(join(docsDir, 'content', `${lang.code}.html`), 'utf8'));
  const out = join(docsDir, lang.path, 'index.html');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, page(lang, meta, main, code));
  built.push(lang.code);
}
